import assert from 'assert/strict'
import * as DM from '../src/domain/domain.mjs'


//輪末摘要之「待核對」之最小收窄(規則 R-REC-39; R-REC-32 之機械提示): 欄內之字樣只出現在「組成對照 / 重放 / 同分次序之結果同號 / 異號」之句者不列
//  spec: ①句 = 以句末之標點(句號、分號、驚嘆號、問號〔全形與半形〕、換行)切; 逗號、頓號不切
//        ②一句不列之條件(全部成立): 同句提到組成對照 / 重放 / 同分次序;句中之字樣皆為前字為「同」或「異」之「號」(同句有保留期 / 他標 / 他幣 / holdout 或其他之「號」⇒ 照列)
//        ③欄內至少一句照列 ⇒ 列該欄(依原有之欄序); 未觸及排除條件者與改前逐字相同(寧可多列)
//  以下之句皆為合成(不取自任何使用端之文件)
let S = (d) => DM.signsMentionOf(d)
let doc = (o = {}) => ({
    guidance: { directions: (o.dirs || ['回測期之窗軸平原', '驗證']).map((rationale) => ({ rationale })) },
    synthesis: { overview: { families: [], coverage: { verdict: 'concentrated', why: o.cov || 'w' }, progress: { verdict: 'flat', why: o.pro || 'w' }, localOptimum: { risk: 'high', why: o.lo || 'w' }, blindSpots: [], adjust: o.adj || '向內 1', prevReview: '' } },
})

describe('輪末摘要之「待核對」:組成對照 / 重放 / 同分次序之同號 / 異號不列(R-REC-39)', function () {
    it('不列:同句提到組成對照 / 重放 / 同分次序而字樣只有「同號 / 異號」(各欄;句中另有逗號、頓號亦同一句)', () => {
        for (let s of [
            '三組組成對照皆同號為正。',
            '兩次重放之超額同號,作用量小。',
            '各同分次序之重放異號 ⇒ 不穩定;',
            '內建組成對照與近期版同號為正者只有一個家族',
            '甲、乙兩版之組成對照異號、量小!',
            '三種組成對照皆過,兩抽同號。',
            '同分次序三組皆同號?',
        ]) {
            assert.deepEqual(S(doc({ dirs: [s], adj: s, cov: s, pro: s, lo: s })), [], s)
        }
        //逗號(全形、半形)與頓號不切句
        for (let p of ['，', ',', '、']) {
            assert.deepEqual(S(doc({ adj: `三種組成對照皆過${p}皆同號` })), [], JSON.stringify(p))
        }
        //一欄多句皆屬可排除者; 不含字樣之句不影響
        assert.deepEqual(S(doc({ adj: '組成對照同號。重放亦同號;同分次序之重放異號\n組成對照與重放同號' })), [])
        assert.deepEqual(S(doc({ adj: '組成對照同號。其餘照舊。', lo: '先看分布;重放同號' })), [])
    })

    it('照列(應列之句型):保留期 / 他標 / 他幣 / holdout 之句(即使同句有組成對照之同號)、其他之「號」、未提組成對照 / 重放 / 同分次序之同號、主詞在另一句者', () => {
        let cases = [
            '保留期之號皆正。',
            '他標之號為負',
            '他幣皆同號',
            '組成對照同號、保留期之號亦正。',
            '重放同號,其他標的之號未讀',
            '組成對照同號;HOLDOUT 皆正',
            '組成對照之正負號皆正。',
            '組成對照同號,入樹後再讀號',
            '兩抽同號、量小。',
            '三者同號為正。',
            '三種組成對照皆過。皆同號。',
            '三種組成對照皆過;皆同號',
            '三種組成對照皆過\n皆同號',
            '三種組成對照皆過!皆同號',
            '三種組成對照皆過?皆同號',
            '組成對照同號;各節點之號另見共同儲存區',
            '依組成對照之正號排序',
            '重放同他幣',
            //句末標點之全形(句號、分號、驚嘆號、問號)與半形(分號、驚嘆號、問號)、換行
            ...['。', '；', '！', '？', ';', '!', '?', '\n'].map((p) => `三種組成對照皆過${p}皆同號`),
        ]
        for (let s of cases) {
            assert.deepEqual(S(doc({ dirs: [s, '驗證'] })), ['方向 1 之理由'], s)
            assert.deepEqual(S(doc({ lo: s })), ['局部最佳點之風險之依據'], s)
        }
    })

    it('欄級:各欄獨立判定、依原有之欄序列出;可排除之句與照列之句同欄 ⇒ 列該欄', () => {
        let d = doc({ dirs: ['組成對照同號。', '他幣之號', '重放異號'], adj: '組成對照同號。兩抽同號。', cov: '同分次序同號', pro: '保留期', lo: '重放同號;正負號另議' })
        assert.deepEqual(S(d), ['方向 2 之理由', '整體研判之調整', '進度之依據', '局部最佳點之風險之依據'])
    })

    it('逐字不變:未觸及排除條件之文件之回傳與改前相同(改前之回傳以字面寫出)', () => {
        //以下皆無「組成對照 / 重放 / 同分次序」, 或有之而另有其他字樣 ⇒ 新判定不作用
        assert.deepEqual(S(doc()), [])
        assert.deepEqual(S(doc({ dirs: ['入樹以取得保留期之號', 'x', '他標之內容'] })), ['方向 1 之理由', '方向 3 之理由'])
        assert.deepEqual(S(doc({ dirs: ['正負號'], adj: '保留期', cov: '他標', pro: 'holdout', lo: '他幣' })), ['方向 1 之理由', '整體研判之調整', '集中度之依據', '進度之依據', '局部最佳點之風險之依據'])
        assert.deepEqual(S(doc({ adj: '訊號之同號', lo: '依同號排序' })), ['整體研判之調整', '局部最佳點之風險之依據'])
        assert.deepEqual(S(doc({ adj: '組成對照之號碼與編號' })), [], '本來就不列者照舊不列')
        assert.deepEqual(S(doc({ cov: '組成對照同號、保留期之號' })), ['集中度之依據'])
    })
})
